"""Turns every value test of the coupon example suite into a Lean theorem.

Each theorem is closed by `decide`: a kernel-checked certificate that the
test is an instance of the model in examples/coupon/lean/CouponModel.lean.
A test the model disagrees with would fail to check. Tests that make no
claim about values (`is defined`, `does not throw`, `does not mutate the
input`) have nothing to translate and are listed as such.

Usage: python3 experiments/derivation/lean_cases.py  (writes lean/Cases.lean)
"""

import re

SRC = "examples/coupon/test/coupon.test.ts"
OUT = "examples/coupon/lean/Cases.lean"

src = open(SRC).read()
CARTS = {"one": "[⟨1000, 1⟩]", "two": "[⟨1000, 1⟩, ⟨500, 2⟩]", "[]": "[]"}


def cart(expr):
    expr = expr.strip()
    if expr in CARTS:
        return CARTS[expr]
    m = re.search(r"Array\.from\(\{ length: (\d+) \}, \(\) => \(\{ priceCents: (\d+), quantity: (\d+) \}\)\)", expr)
    if m:
        return f"List.replicate {m.group(1)} ⟨{m.group(2)}, {m.group(3)}⟩"
    items = re.findall(r"priceCents:\s*(\d+),\s*quantity:\s*(\d+)", expr)
    if items:
        return "[" + ", ".join(f"⟨{p}, {q}⟩" for p, q in items) + "]"
    raise ValueError(f"cannot read cart {expr!r}")


def coupon(expr):
    if not expr:
        return "none"
    kind = re.search(r'kind: "(\w+)"', expr).group(1)
    mn = re.search(r"minSubtotalCents: (\d+)", expr)
    mn = f"some {mn.group(1)}" if mn else "none"
    if kind == "percent":
        return f"some ⟨.percent {re.search(r'percent: (-?\d+)', expr).group(1)}, {mn}⟩"
    return f"some ⟨.fixed {re.search(r'amountCents: (\d+)', expr).group(1)}, {mn}⟩"


def split_args(args):
    depth = 0
    for i, ch in enumerate(args):
        depth += ch in "[({"
        depth -= ch in "])}"
        if ch == "," and depth == 0:
            return args[:i], args[i + 1 :].strip()
    return args, ""


tests = re.findall(r'it\("([^"]+)", \(\) => \{(.*?)\n  \}\);', src, re.S)
lines = [
    "import CouponModel",
    "",
    "/-! Every value test of the agent-style suite, as a theorem about the model.",
    "    Generated by experiments/derivation/lean_cases.py; each `decide` is a",
    "    kernel-checked certificate that the test is an instance of the model. -/",
    "",
    "open CouponModel",
    "",
]
translated, skipped = 0, []
for name, body in tests:
    local = re.search(r"const items = (Array\.from\(.*?\)\));", body, re.S)
    m = re.search(r"expect\(\s*(applyCoupon|subtotal)\((.*?)\)\s*,?\s*\)\.(toBe|toBeGreaterThanOrEqual)\((\d+)\)", body, re.S)
    if not m:
        skipped.append(name)
        continue
    fn, args, matcher, val = m.groups()
    args = args.strip()
    if local and args.startswith("items"):
        args = local.group(1) + args[len("items") :]
    if fn == "subtotal":
        lhs = f"subtotal ({cart(args)})"
    else:
        c, k = split_args(args)
        lhs = f"apply ({cart(c)}) ({coupon(k)})"
    rel = "=" if matcher == "toBe" else "≥"
    lines += [f"-- {name}", f"example : {lhs} {rel} {val} := by decide"]
    translated += 1

lines += ["", "-- No value claim to translate: " + "; ".join(skipped)]
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"{translated} theorems, {len(skipped)} tests without a value claim: {', '.join(skipped)}")
